SCRIPT_INCLUDES = {"build.ps1", "fetch-librime.ps1", "make-icon.ps1"}

ROOT_FILES = ["CMakeLists.txt", "VERSION", "THIRD_PARTY_NOTICES.md"]

# A fork that still says Yingwu or hengma anywhere is a fork that will confuse
# the next person. Refuse to write one.
FORBIDDEN = ("Yingwu", "yingwu", "YINGWU", "hengma", "Hengma", "HENGMA",
             "衡码", "应物输入法", "hm::", "HM_", "hmcommon.h",
             "TextService.ico", "LEGACY", "legacy", "0.57", "0.3.0-alpha",
             "0.3.1-alpha",
             # 应物's CLSID, profile GUID and preserved-key GUID. Sharing any
             # of them would make the two products evict each other.
             "57a9a4da", "57A9A4DA", "c22c0423", "C22C0423",
             "35c3b3a4", "35C3B3A4")


def read(path: pathlib.Path):
    raw = path.read_bytes()
    bom = b""
    if raw.startswith(b"\xef\xbb\xbf"):
        bom = raw[:3]
        raw = raw[3:]
    return raw.decode("utf-8"), bom


def replace_all(text: str, pairs, where: str, changed: list, strict: bool) -> str:
    """Apply literal replacements.

    ``strict`` pairs must hit: they name something a file is expected to
    contain exactly one of, so a miss means upstream moved it and the port
    quietly stopped rebranding that spot.
    """
    for old, new in pairs:
        if old not in text:
            if strict:
                print(f"  MISS  {where}: {old[:60]!r}", file=sys.stderr)
            continue
        text = text.replace(old, new)
        changed.append(where)
    return text


def port_file(source: pathlib.Path, target: pathlib.Path, key: str,
              label: str, check: bool) -> int:
    """Port one file. ``key`` is its path upstream, ``label`` its path here."""
    text, bom = read(source)
    changed: list = []

    for block in DELETIONS.get(key, []):
        if block not in text:
            print(f"  MISS  {key}: block deletion", file=sys.stderr)
            continue
        text = text.replace(block, "")
        changed.append(key)

    text = replace_all(text, IDENTITY, key, changed, strict=False)
    text = replace_all(text, MECHANICAL, key, changed, strict=False)
    text = replace_all(text, EXTRA_PAIRS.get(key, []), key, changed, strict=True)

    leftovers = [token for token in FORBIDDEN if token in text]
    for token in leftovers:
        print(f"  LEFTOVER {label}: {token!r}", file=sys.stderr)

    if not check:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(bom + text.encode("utf-8"))
    print(f"port  {label}  ({len(changed)} changes)")
    return len(leftovers)


def walk(source_dir: pathlib.Path, suffixes: set, exclude: set):
    for path in sorted(source_dir.rglob("*")):
        if not path.is_file():
            continue
        if path.suffix.lower() not in suffixes:
            continue
        if any(part in exclude for part in path.relative_to(source_dir).parts):
            continue
        yield path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="report what would change, write nothing")
    args = parser.parse_args()

    if not UPSTREAM.is_dir():
        print(f"missing upstream tree: {UPSTREAM}", file=sys.stderr)
        return 1

    renamed = IDENTITY + MECHANICAL
    problems = 0
    count = 0

    for source_name, dest_name, suffixes, exclude in TREES:
        source_dir = UPSTREAM / source_name
        for path in walk(source_dir, suffixes, exclude):
            leaf = path.relative_to(source_dir).as_posix()
            if source_name == "scripts" and leaf not in SCRIPT_INCLUDES:
                continue
            # Keyed by the path upstream, so the tables above read as "the file
            # in 应物's tree", and every key is unique across the trees.
            key = f"{source_name}/{leaf}"
            relative = leaf
            for old, new in renamed:
                relative = relative.replace(old, new)
            problems += port_file(path, REPO / dest_name / relative, key,
                                  f"{dest_name}/{relative}", args.check)
            count += 1

    for name in ROOT_FILES:
        problems += port_file(UPSTREAM / name, REPO / name, name, name,
                              args.check)
        count += 1

    print(f"\n{count} files")
    if problems:
        print(f"{problems} leftover identity tokens -- fix the tables above",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
