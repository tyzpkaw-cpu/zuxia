#!/usr/bin/env python3
"""Import the 应物 input method into this repository as 足下.

应物音形足下输入法 and 应物输入法 are two products built from one text service.
The TSF layer, the candidate window, the language-bar indicator, the installer
and the build scripts are all scheme-agnostic: they open a librime session,
route keys and register with Windows. What differs is identity -- the scheme
id, the dictionary names, the install and user directories, the registry keys
and the CLSIDs.

This script makes that fork mechanically, so that the difference between the
two trees is exactly the token table below and nothing accidental:

    ../hengma-native/{src,installer,scripts}, CMakeLists.txt, VERSION,
        THIRD_PARTY_NOTICES.md
      ->  src/, installer/, scripts/, CMakeLists.txt, VERSION,
          THIRD_PARTY_NOTICES.md

Run it from anywhere:

    python tools/port_from_yingwu.py

It overwrites the ported files completely. Re-running it after editing them by
hand discards those edits, so treat the upstream tree as the source of truth
and put local differences in the EXTRA_PAIRS / DELETIONS tables here.

Two things are deliberately NOT ported:

* Icons. `src/ZuxiaTSF.ico` and `installer/setup/app.ico` are generated by
  `scripts/make-icon.ps1`, which renders a character. 应物 uses 应; a sibling
  that shares its icon is hard to tell apart in the Win+Space list, so 足下
  renders its own. Run:
      pwsh scripts/make-icon.ps1 -Char 足 -Out src/ZuxiaTSF.ico
      pwsh scripts/make-icon.ps1 -Char 足 -Out installer/setup/app.ico
* Build products: payload.cab/.ddf, payload_info.h, setup.u16.rc, *.res,
  *.exe and obj_*/ under installer/setup are generated by the build.
"""

